<?php

namespace MediaCloud\Plugin\Tools\VideoPlayer\Players\MediaChrome;

use MediaCloud\Plugin\Tools\VideoPlayer\VideoPlayerToolSettings;

/**
 * @property string mediaChromeConfigJSON
 * @property MediaChromeConfig mediaChromeConfig
 */
class MediaChromePlayerSettings extends VideoPlayerToolSettings {
	/**
	 * Map of property names to setting names
	 * @var string[]
	 */
	protected $mediaChromeSettingsMap = [
		'mediaChromeConfigJSON' => ['media-cloud-player-media-chrome-config', null, '{}'],
	];

	/**
	 * @var MediaChromeConfig|null
	 */
	protected $config = null;

	public function __construct() {
		$this->settingsMap = array_merge($this->settingsMap, $this->mediaChromeSettingsMap);
	}

	public function __get($name) {
		if ($name === 'mediaChromeConfig') {
			if ($this->config) {
				return $this->config;
			}

			$this->config = new MediaChromeConfig($this->mediaChromeConfigJSON);
			return $this->config;
		}

		return parent::__get($name); // TODO: Change the autogenerated stub
	}

	public function __isset($name) {
		if ($name === 'mediaChromeConfig') {
			return true;
		}

		return parent::__isset($name); // TODO: Change the autogenerated stub
	}
}