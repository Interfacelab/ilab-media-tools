<?php

namespace MediaCloud\Plugin\Tools\Video\Driver\APIVideo;

use MediaCloud\Plugin\Tools\ToolSettings;

/**
 * @property string|null $apiKey
 * @property bool $sandboxMode
 * @property string|null $webhookHost
 * @property bool $deleteFromStream
 * @property bool $processUploads
 * @property string|null $webhookUrl
 */
class APIVideoSettings extends ToolSettings {
	/**
	 * Map of property names to setting names
	 * @var string[]
	 */
	protected $settingsMap = [
		'apiKey' => ['media-cloud-apivideo-api-key', null, null],
		'sandboxMode' => ['media-cloud-apivideo-sandbox-mode', null, false],
		'webhookHost' => ['media-cloud-apivideo-webhook-host', null, null],
		'deleteFromStream' => ['media-cloud-apivideo-delete-from-stream', null, true],
		'processUploads' => ['media-cloud-apivideo-process-uploads', null, true],
	];

	public function __get($name) {
		if ($name === 'webhookUrl') {
			return trailingslashit($this->webhookHost) . '__api-video/webhook';
		}

		return parent::__get($name); // TODO: Change the autogenerated stub
	}

	public function __isset($name) {
		if ($name === 'webhookUrl') {
			return true;
		}

		return parent::__isset($name); // TODO: Change the autogenerated stub
	}
}