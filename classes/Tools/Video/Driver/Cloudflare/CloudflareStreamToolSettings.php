<?php

namespace MediaCloud\Plugin\Tools\Video\Driver\Cloudflare;

use MediaCloud\Plugin\Tools\ToolSettings;

/**
 * @property string|null $accountId
 * @property string|null $apiKey
 * @property string|null $cdnUrl
 * @property string|null $webhookHost
 * @property string $webhookUrl
 * @property bool $deleteFromStream
 * @property bool $processUploads
 */
class CloudflareStreamToolSettings extends ToolSettings {
	/**
	 * Map of property names to setting names
	 * @var string[]
	 */
	protected $settingsMap = [
		'accountId' => ['media-cloud-cloudflare-stream-account-id', null, null],
		'apiKey' => ['media-cloud-cloudflare-stream-api-key', null, null],
		'cdnUrl' => ['media-cloud-cloudflare-stream-cdn-url', null, null],
		'webhookHost' => ['media-cloud-cloudflare-stream-webhook-host', null, null],
		'processUploads' => ['media-cloud-cloudflare-stream-process-uploads', null, true],
		'deleteFromStream' => ['media-cloud-cloudflare-stream-delete-from-stream', null, true],
	];

	public function __get($name) {
		if ($name === 'webhookUrl') {
			return trailingslashit($this->webhookHost) . '__cloudflare-stream/webhook';
		}

		return parent::__get($name); // TODO: Change the autogenerated stub
	}

	public function __isset($name) {
		if ($name === 'webhookUrl') {
			return true;
		}

		return parent::__isset($name); // TODO: Change the autogenerated stub
	}
}