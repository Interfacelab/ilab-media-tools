<?php

namespace MediaCloud\Plugin\Tools\Video\Driver\Cloudflare;

/**
 * @property bool $useEmbeddedPlayer
 * @property array $watermarkData
 * @property string $watermarkJSON
 * @property bool $secureVideo
 * @property int $secureExpiration
 * @property string|null $allowedOrigins
 * @property bool $rotateKeys
 * @property int $keyExpiration
 * @property bool $excludePrivateREST
 */
class CloudflareStreamToolProSettings extends CloudflareStreamToolSettings {
	/**
	 * Map of property names to setting names
	 * @var string[]
	 */
	protected $proSettingsMap = [
		'useEmbeddedPlayer' => ['media-cloud-cloudflare-use-embed-player', null, true],
		'watermarkJSON' => ['media-cloud-cloudflare-stream-watermark', null, true],
		'secureVideo' => ['media-cloud-cloudflare-secure-video', null, false],
		'secureExpiration' => ['media-cloud-cloudflare-secure-video-expiration', null, 0],
		'allowedOrigins' => ['media-cloud-cloudflare-allowed-origins', null, null],
		'rotateKeys' => ['media-cloud-cloudflare-rotate-keys', null, false],
		'keyExpiration' => ['media-cloud-cloudflare-key-expiration', null, 1],
		'excludePrivateREST' => ['media-cloud-cloudflare-exclude-private-from-rest', null, true],
	];


	public function __construct() {
		$this->settingsMap = array_merge($this->settingsMap, $this->proSettingsMap);
	}

	public function __get($name) {
		if ($name === 'watermarkData') {
			$s = $this->watermarkJSON;
			if (empty($s)) {
				return [];
			}

			return json_decode($s, true);
		}

		return parent::__get($name); // TODO: Change the autogenerated stub
	}

	public function __set($name, $value) {
		if ($name === 'watermarkData') {
			$this->watermarkJSON = !empty($value) ? json_encode($value) : null;
		}

		return parent::__set($name,$value); // TODO: Change the autogenerated stub
	}

	public function __isset($name) {
		if ($name === 'watermarkData') {
			return true;
		}

		return parent::__isset($name); // TODO: Change the autogenerated stub
	}
}