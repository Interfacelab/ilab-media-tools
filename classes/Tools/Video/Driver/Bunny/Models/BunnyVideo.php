<?php

namespace MediaCloud\Plugin\Tools\Video\Driver\Bunny\Models;

use MediaCloud\Plugin\Model\Model;

/**
 * @property string video_id
 * @property int $attachment_id
 * @property int $status
 * @property int $private
 * @property string|null $subtitles
 * @property array{ local:bool, cc: bool, name: string, language_code: string, url: string } $subtitlesData
 */
class BunnyVideo extends Model {
	const STATUS_QUEUED = 0;
	const STATUS_PROCESSING = 1;
	const STATUS_ENCODING = 2;
	const STATUS_FINISHED = 3;
	const STATUS_RESOLUTION = 4;
	const STATUS_FAILED = 5;
	const STATUS_PRESIGNED_UPLOAD_STARTED = 6;
	const STATUS_PRESIGNED_UPLOAD_FINISHED = 7;
	const STATUS_PRESIGNED_UPLOAD_FAILED = 8;
	const STATUS_CAPTIONS_GENERATED = 9;
	const STATUS_TITLE_OR_DESCRIPTION_GENERATED = 10;

	/** @var string  */
	protected $video_id;

	/** @var int  */
	protected $status;

	/** @var int */
	protected $attachment_id;

	/** @var ?string */
	protected $subtitles;

	protected $modelProperties = [
		'video_id' => '%s',
		'status' => '%d',
		'attachment_id' => '%d',
		'private' => '%d',
		'subtitles' => '%s',
	];

	public static function table() {
		global $wpdb;
		return "{$wpdb->base_prefix}mcloud_bstream_videos";
	}

	public static function statusString($status) {
		switch($status) {
			case static::STATUS_QUEUED: return 'Queued';
			case static::STATUS_PROCESSING: return 'Processing';
			case static::STATUS_ENCODING: return 'Encoding';
			case static::STATUS_FINISHED: return 'Finished';
			case static::STATUS_RESOLUTION: return 'Resolution';
			case static::STATUS_FAILED: return 'Failed';
			case static::STATUS_PRESIGNED_UPLOAD_STARTED: return 'Presigned Upload Started';
			case static::STATUS_PRESIGNED_UPLOAD_FINISHED: return 'Presigned Upload Finished';
			case static::STATUS_PRESIGNED_UPLOAD_FAILED: return 'Presigned Upload Failed';
			case static::STATUS_CAPTIONS_GENERATED: return 'Captions Generated';
			case static::STATUS_TITLE_OR_DESCRIPTION_GENERATED: return 'Title or Description Generated';
			default: return 'Unknown';
		}
	}

	public static function video($videoId) {
		global $wpdb;

		$table = static::table();
		$rows = $wpdb->get_results($wpdb->prepare("select * from {$table} where video_id = %s", $videoId));

		foreach($rows as $row) {
			return new static($row);
		}

		return null;
	}

	public static function videoForAttachment($attachmentId) {
		global $wpdb;

		$table = static::table();
		$rows = $wpdb->get_results($wpdb->prepare("select * from {$table} where attachment_id = %s", $attachmentId));

		foreach($rows as $row) {
			return new static($row);
		}

		return null;
	}

	public static function findOrCreate($videoId) {
		$video = static::video($videoId);
		if (!empty($video)) {
			return $video;
		}

		$video = new BunnyVideo();
		$video->video_id = $videoId;
		return $video;
	}

	public function __get($name) {
		if ($name === 'subtitlesData') {
			$s = $this->subtitles;
			if (empty($s)) {
				return [];
			}

			return json_decode($s, true);
		}

		return parent::__get($name); // TODO: Change the autogenerated stub
	}

	public function __set($name, $value) {
		if ($name === 'subtitlesData') {
			$this->subtitles = json_encode($value);
			return;
		}

		parent::__set($name, $value); // TODO: Change the autogenerated stub
	}

	public function __isset($name) {
		if ($name === 'subtitlesData') {
			return true;
		}

		return parent::__isset($name); // TODO: Change the autogenerated stub
	}
}